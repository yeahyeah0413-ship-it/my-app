/** 문의 유형 */
export type Category = "작성기준" | "증빙" | "결재선" | "예산한도";

/** 답변 뒤에 덧붙일 소속별 안내의 종류 */
export type DepartmentNote = "approvalBox" | "chairmanException" | "approver";

/**
 * 답변 안의 금액별 구간 하나.
 * upTo 이하 금액이면 이 구간이 해당된다. 답변이 텍스트면 label(문자열, answer 안에 정확히
 * 있어야 함)을 강조하고, 표가 있으면 rowId(해당 표 행의 id)를 강조한다.
 * 한 답변에 결재선 표가 여러 벌(예: 사전품의 완료/미완료) 있으면 group으로 묶어서 표마다 하나씩 고른다.
 */
export type AmountTier = {
  group?: string;
  upTo: number;
  label?: string;
  rowId?: string;
};

/** 표의 한 행. id를 주면 amountTiers의 rowId로 연결해 그 행만 강조할 수 있다. */
export type AnswerTableRow = {
  id?: string;
  cells: string[];
};

/** 답변에 곁들이는 표. 텍스트로 나열하기보다 표가 더 읽기 쉬운 내용(금액 구간표 등)에 쓴다. */
export type AnswerTable = {
  title?: string;
  headers: string[];
  rows: AnswerTableRow[];
};

/**
 * 질문에 특정 단어(국가명 등)가 있으면 answer 안의 다른 문구를 함께 강조하고 싶을 때 쓴다.
 * 예: 질문에 "아프리카"가 있으면 "· A급지:" 부분도 같이 강조해, 어느 급지인지 바로 보이게 한다.
 * label은 answer 문자열 안에 정확히, 한 번만 있어야 한다.
 */
export type MatchTier = {
  match: string[];
  label: string;
};

/** 사내 가이드 문서 한 건 */
export type GuideEntry = {
  id: string;
  category: Category;
  /** 매칭에 사용할 키워드 */
  keywords: string[];
  /** 답변 본문 */
  answer: string;
  /** 근거 문서 (답변에 항상 함께 표시) */
  source: string;
  /** 소속이 선택된 경우에만 답변 뒤에 덧붙일 안내 (없으면 소속과 무관하게 같은 답변) */
  notes?: DepartmentNote[];
  /**
   * 문서에 실제 값(예산 잔액 등)이 없거나 다른 팀의 최신 공지를 따라야 해서
   * 답변으로 확정하지 않고 담당자에게 안내할 항목에 표시한다.
   * true면 category 기본 담당자, Owner를 주면 그 담당자로 안내한다.
   */
  routeToOwner?: boolean | Owner;
  /** 질문에서 금액이 읽히면, 해당하는 구간만 답변에서 강조 표시하기 위한 정보 */
  amountTiers?: AmountTier[];
  /** 질문의 특정 단어에 맞춰 answer 안의 다른 문구도 함께 강조하고 싶을 때 쓴다 */
  matchTiers?: MatchTier[];
  /** 텍스트 나열보다 표가 더 읽기 쉬운 내용을 별도로 담는다. 여러 벌이면 순서대로 표시된다. */
  tables?: AnswerTable[];
  /** 표 아래에 덧붙일 부연 설명 (표로 옮기지 않은 나머지 텍스트) */
  afterNote?: string;
};

/** 담당자 정보 */
